  async createProduct(tenantId: string, data: any) {
    const code = data.code && data.code.trim() !== ''
      ? data.code.trim()
      : generateCode(data.name || 'PRD');

    const parseDec = (val: any, def: number) => {
      if (val === null || val === undefined || val === '') return def;
      const n = parseFloat(String(val).replace(/,/g, '.'));
      return isNaN(n) ? def : n;
    };

    const product = await this.prisma.product.create({
      data: {
        tenantId,
        code,
        name: data.name,
        brand: data.brand || null,
        model: data.model || null,
        category: data.category || null,
        type: data.type || null,
        unit: data.unit || 'Unidad',
        location: data.location || null,
        description: data.description || null,
        attributes: (process.env.VENTECH_DESKTOP === "1" && typeof data.attributes === "object" && data.attributes !== null) ? JSON.stringify(data.attributes) : (data.attributes || null),
        priceUSD: data.priceUSD ? parseDec(data.priceUSD, 0) : 0,
        costUSD: data.costUSD ? parseDec(data.costUSD, 0) : null,
        stock: parseDec(data.stock, 0),
        minStock: parseDec(data.minStock, 0),
        status: data.status || 'ACTIVO',
        isExempt: data.isExempt || false,
      },
    });
    await this.audit.logAction('CREATE_PRODUCT', 'Product', product.id, undefined, product, undefined, tenantId);
    return product;
  }

  async updateProduct(tenantId: string, id: string, data: any) {
    if (data.attributes && typeof data.attributes !== 'string' && process.env.DATABASE_URL?.startsWith('file:')) { data.attributes = JSON.stringify(data.attributes); }
    const existing = await this.prisma.product.findUnique({ where: { id } });
    if (!existing || existing.tenantId !== tenantId) throw new Error('Not found');

    const parseDec = (val: any) => {
      if (val === null || val === undefined || val === '') return undefined;
      const n = parseFloat(String(val).replace(/,/g, '.'));
      return isNaN(n) ? undefined : n;
    };

    const updateData: any = { ...data };
    if (updateData.priceUSD !== undefined) updateData.priceUSD = parseDec(updateData.priceUSD);
    if (updateData.costUSD !== undefined) updateData.costUSD = updateData.costUSD ? parseDec(updateData.costUSD) : null;
    if (updateData.stock !== undefined) updateData.stock = parseDec(updateData.stock);
    if (updateData.minStock !== undefined) updateData.minStock = parseDec(updateData.minStock);
    
    delete updateData.id;
    delete updateData.tenantId;
    delete updateData.createdAt;
    delete updateData.updatedAt;

    if (process.env.VENTECH_DESKTOP === '1' && typeof updateData.attributes === 'object' && updateData.attributes !== null) updateData.attributes = JSON.stringify(updateData.attributes);
    const updated = await this.prisma.product.update({ where: { id }, data: updateData });
    await this.audit.logAction('UPDATE_PRODUCT', 'Product', id, existing, updated, undefined, tenantId);
    return updated;
  }

  async deleteProduct(tenantId: string, id: string) {
    const existing = await this.prisma.product.findUnique({ where: { id } });
    if (!existing || existing.tenantId !== tenantId) throw new Error('Not found');
    const deleted = await this.prisma.product.delete({ where: { id } });
    await this.audit.logAction('DELETE_PRODUCT', 'Product', id, existing, undefined, undefined, tenantId);
    return deleted;
  }

