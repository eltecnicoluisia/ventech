function generateCode(name: string): string {
  const prefix = name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, '')
    .slice(0, 3);
  const rnd = Math.floor(100 + Math.random() * 900);
  return `${prefix}-${rnd}`;
}

// Convertir string "123,45" a Float para Decimal
function parseDec(val: any): number {
  if (typeof val === 'number') return val;
  if (!val) return 0;
  return parseFloat(val.toString().replace(/,/g, '.'));
}

